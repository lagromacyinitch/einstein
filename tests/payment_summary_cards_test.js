const fs = require('fs'), vm = require('vm'), assert = require('assert/strict');
const html = fs.readFileSync('public/admin.html','utf8');
const start = html.indexOf('    function updateBalanceSummaryCards(data) {');
const source = html.slice(start,html.indexOf('\n    function _renderBalanceMonitoringFromCache()',start));
const elements = Object.fromEntries(['bm-total-receivables','bm-total-collected','bm-count-with-balance','bm-count-settled','bm-summary-status'].map(id=>[id,{style:{},nextElementSibling:{}}]));
const context=vm.createContext({document:{getElementById:id=>elements[id]}});
vm.runInContext('let balanceSummaryLive=true;'+source,context);
const row=(fee,paid)=>({adminRec:{total_fee:fee,paid_amount:paid},totalFee:fee,status:'partial'});
context.updateBalanceSummaryCards([row(3300,1000),row(500,500),{totalFee:3300,adminRec:null}]);
assert.equal(elements['bm-total-receivables'].textContent,'\u20b12,300.00');
assert.equal(elements['bm-total-collected'].textContent,'\u20b11,500.00');
assert.equal(elements['bm-count-with-balance'].textContent,1);
assert.equal(elements['bm-count-settled'].textContent,1);
assert.match(elements['bm-summary-status'].textContent,/2 of 3/);
context.updateBalanceSummaryCards([row(500,null),row(500,-1)]);
assert.equal(elements['bm-total-collected'].textContent,'Needs review');
context.updateBalanceSummaryCards([]);
assert.equal(elements['bm-total-collected'].textContent,'\u20b10.00');
context.updateBalanceSummaryCards([row(500,600)]);
assert.equal(elements['bm-total-collected'].textContent,'\u20b1600.00');
assert.equal(elements['bm-total-receivables'].textContent,'\u20b10.00');
vm.runInContext('balanceSummaryLive=false',context);
context.updateBalanceSummaryCards([row(500,100)]);
assert.match(elements['bm-summary-status'].textContent,/Saved data/);
assert.equal(elements['bm-total-collected'].textContent,'\u20b1100.00');
console.log('PASS: partial totals, exclusions, unknown vs zero, overpayments and cached-data labels.');
